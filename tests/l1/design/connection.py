    lines += ['## Margins and bandwidth (linear model, relay closed)', '',
              'Margins are open-loop properties; the closed loop is described by its bandwidth and resonance peak. Frequencies in the dq frame. With exact feedforward the loop is the current PI alone; without the PI it is the feedforward alone.', '',
              '| Case | Open loop: crossover (Hz) | Open loop: phase margin (°) | Open loop: gain margin (dB) | Closed loop: bandwidth −3 dB (Hz) | Closed loop: peak (dB) | Closed loop: peak at (Hz) |',
              '|---|---|---|---|---|---|---|']
    for label, m, lm in rows:
        if lm: lines.append(f"| {label} | {f(lm['crossover_Hz'])} | {f(lm['pm_deg'])} | {f(lm['gm_dB'])} | {f(lm['bandwidth_Hz'])} | {f(lm['peak_dB'])} | {f(lm['peak_Hz'])} |")
    lines += ['', '![Open loop](bode_open.png)', '', '![Closed loop](bode_closed.png)', '', '## Connection transient (time domain)', '', *METRIC_HEAD]
