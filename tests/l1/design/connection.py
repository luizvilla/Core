"""Design aid only (ADR 0004): INFO results that decide whether an idea is worth a switched run."""
import argparse, math
from pathlib import Path
import numpy as np
import ladder as ld
import loop_linear as ll

TARGET_PEAK, TARGET_SETTLE_MS = 0.3, 20.0   # provisional target for the ideal case (proposed, to be confirmed by Luiz Villa)
SETTLE_BAND = 0.05
BASE = dict(kp=1.0, ti=0.005, kr_i=2000.0, adv=0.5)
RUNG1 = dict(pll=False, caps=False, delay=ld.TS)
RUNG4 = dict(pll=True, caps=True, delay=80e-6)
COLORS = ['#2a78d6', '#eb6834', '#1baf7a', '#eda100']


def metrics(rg, lg, **kw):
    r = ld.run(rg, lg, trip=1e9, **kw); t, ig = r['t'], r['ig']; tc = r['t_contact']
    after = t >= tc; pre = after & (t < ld.T_STEP)
    m10, m20, m5 = after & (t < tc + 0.01), after & (t < tc + 0.02), after & (t < tc + 0.005)
    out_band = np.where(pre & (np.abs(ig) > SETTLE_BAND))[0]
    settle = float(1e3 * (t[out_band[-1]] - tc)) if len(out_band) else 0.0
    res = {'peak10': float(np.abs(ig[m10]).max()), 'peak20': float(np.abs(ig[m20]).max()), 'settle_ms': settle,
           'real5': float(np.abs(ig[m5]).max()), 'seen5': float(np.hypot(r['idm'][m5], r['iqm'][m5]).max()),
           'th_dev_deg': float(np.degrees(np.abs(r['th_err'][pre] - r['th_err'][after][0]).max())),
           'w_dev_hz': float(np.abs(r['w'][pre] - ld.W0).max() / (2 * math.pi)),
           'trips': bool(np.abs(ig[after]).max() > ld.TRIP), 'final_id': float(r['idm'][t > ld.T_END - 0.04].mean()),
           'trace': (t[after & (t < tc + 0.06)] - tc, ig[after & (t < tc + 0.06)])}
    res['meets'] = res['peak10'] < TARGET_PEAK and res['settle_ms'] < TARGET_SETTLE_MS
    return res


f = lambda v, d=3: '—' if v is None or (isinstance(v, float) and not math.isfinite(v)) else f'{v:.{d}g}'


def style(ax):
    ax.set_facecolor('#fcfcfb'); ax.grid(True, which='both', color='#e4e3df', lw=0.6)
    for sp in ('top', 'right'): ax.spines[sp].set_visible(False)
    ax.tick_params(colors='#52514e')


def header(test, title, grid, rg, lg, what):
    return [f'# {test}: {title}, {grid} grid', '',
            f'Design test ([ADR 0004](../../../adr/0004-averaged-model-for-fast-evaluation.md)): averaged model, INFO only, no verdict. {what} Grid: {rg} Ω, {lg * 1e3:g} mH. '
            f'Trip disabled so the whole transient is visible; "would trip" compares with the 1.5 A bench trip. '
            f'Provisional target for the ideal case (proposed, to be confirmed): peak below {TARGET_PEAK} A over 10 ms and settling within ±{SETTLE_BAND} A in under {TARGET_SETTLE_MS:g} ms. '
            f'Generated by `tests/l1/design/connection.py`.', '', '## Plant and loop', '', '```mermaid', ld.MERMAID.rstrip(), '```', '']


METRIC_HEAD = ('| Case | Peak, 10 ms (A) | Peak, 20 ms (A) | Settling ±0.05 A (ms) | Meets target | Would trip | Line current, 5 ms (A) | \\|I_dq\\| seen, 5 ms (A) | PLL angle excursion (°) | PLL frequency excursion (Hz) |',
               '|---|---|---|---|---|---|---|---|---|---|')


def metric_row(label, m):
    return (f"| {label} | {f(m['peak10'])} | {f(m['peak20'])} | {f(m['settle_ms'])} | {'yes' if m['meets'] else 'no'} | {'yes' if m['trips'] else 'no'} | "
            f"{f(m['real5'])} | {f(m['seen5'])} | {f(m['th_dev_deg'])} | {f(m['w_dev_hz'])} |")


def test02(grid, out):
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    rg, lg = ld.GRIDS[grid]
    cases = [  # label, time kwargs, linear kwargs (None: no linear row), plotted
        ('a. base: measured feedforward, PI from the command, advance 0.5', {}, {}, True),
        ('b. feedforward from the exact grid voltage', {'ff': 'exact'}, {'ff': 'exact'}, True),
        ('c. no current PI (feedforward alone)', {'pi_from': 'never'}, {'pi': False}, False),
        ('d. no current PI, exact feedforward', {'pi_from': 'never', 'ff': 'exact'}, None, False),
        ('e. advance 0', {'adv': 0.0}, {'adv': 0.0}, True),
        ('f. advance 1 period', {'adv': 1.0}, {'adv': 1.0}, True),
        ('g. exact feedforward, advance 0', {'ff': 'exact', 'adv': 0.0}, {'ff': 'exact', 'adv': 0.0}, False),
        ('h. exact feedforward, advance 1 period', {'ff': 'exact', 'adv': 1.0}, {'ff': 'exact', 'adv': 1.0}, False),
        ('i. PI from the relay feedback (library today)', {'pi_from': 'feedback'}, None, False),
        ('j. exact feedforward, advance 1.5 periods (delay + half a period of hold)', {'ff': 'exact', 'adv': 1.5}, {'ff': 'exact', 'adv': 1.5}, False),
        ('k. advance 1.5 periods', {'adv': 1.5}, {'adv': 1.5}, False)]
    rows, curves = [], []
    for label, tk, lk, plot in cases:
        m = metrics(rg, lg, **{**BASE, **RUNG1, **tk}); lm = None
        if lk is not None:
            lin = ll.loop(caps=False, rg=rg, lg=lg, delay=ld.TS, **{**BASE, **lk}); lm = ll.margins(lin)
            if plot: curves.append((label, lin))
        rows.append((label, m, lm))
    out.mkdir(parents=True, exist_ok=True)
    for key, name, title in (('L', 'bode_open.png', 'Open loop L'), ('T', 'bode_closed.png', 'Closed loop T')):
        fig, (am, ap) = plt.subplots(2, 1, figsize=(8, 6.4), sharex=True, facecolor='#fcfcfb')
        for (label, r), col in zip(curves, COLORS):
            am.semilogx(r['f'], 20 * np.log10(np.abs(r[key])), color=col, lw=1.5, label=label.split(':')[0] if ':' in label else label)
            ap.semilogx(r['f'], np.degrees(np.unwrap(np.angle(r[key]))), color=col, lw=1.5)
        for ax in (am, ap): style(ax)
        am.axhline(0 if key == 'L' else -3, color='#52514e', lw=0.8, ls='-' if key == 'L' else '--')
        am.set_ylabel('Magnitude (dB)'); ap.set_ylabel('Phase (°)'); ap.set_xlabel('Frequency in the dq frame (Hz, offset from 50 Hz)')
        am.set_title(f'{title}, rung 1, {grid} grid', loc='left', fontsize=11); am.legend(frameon=False, fontsize=8)
        fig.tight_layout(); fig.savefig(out / name, dpi=130); plt.close(fig)
    fig, ax = plt.subplots(figsize=(8, 3.6), facecolor='#fcfcfb')
    for (label, m, _), col in zip([r for r in rows if r[0][0] in 'abce'], COLORS):
        ax.plot(1e3 * m['trace'][0], m['trace'][1], color=col, lw=1.2, label=label)
    style(ax); ax.set_xlabel('Time after the contact (ms)'); ax.set_ylabel('Line current (A)')
    ax.set_title(f'Connection transient, rung 1, {grid} grid', loc='left', fontsize=11); ax.legend(frameon=False, fontsize=8)
    fig.tight_layout(); fig.savefig(out / 'transient.png', dpi=130); plt.close(fig)
    lines = header('D-GFL-02', 'source of the connection disturbance in the ideal case', grid, rg, lg,
                   'Rung 1 of D-GFL-01 (averaged L, ideal angle, no filter capacitors, delay one control period), candidate C, contact on a voltage zero crossing; one factor changed at a time.')
    lines += ['## Margins and bandwidth (linear model, relay closed)', '',
              'Margins are open-loop properties; the closed loop is described by its bandwidth and resonance peak. Frequencies in the dq frame. With exact feedforward the loop is the current PI alone; without the PI it is the feedforward alone.', '',
              '| Case | Open loop: crossover (Hz) | Open loop: phase margin (°) | Open loop: gain margin (dB) | Closed loop: bandwidth −3 dB (Hz) | Closed loop: peak (dB) | Closed loop: peak at (Hz) |',
              '|---|---|---|---|---|---|---|']
    for label, m, lm in rows:
        if lm: lines.append(f"| {label} | {f(lm['crossover_Hz'])} | {f(lm['pm_deg'])} | {f(lm['gm_dB'])} | {f(lm['bandwidth_Hz'])} | {f(lm['peak_dB'])} | {f(lm['peak_Hz'])} |")
    lines += ['', '![Open loop](bode_open.png)', '', '![Closed loop](bode_closed.png)', '', '## Connection transient (time domain)', '', *METRIC_HEAD]
    lines += [metric_row(label, m) for label, m, _ in rows]
    lines += ['', '![Transient](transient.png)', '']
    (out / 'report.md').write_text('\n'.join(lines) + '\n'); print('\n'.join(lines[-16:]))


def test03(grid, out):
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    rg, lg = ld.GRIDS[grid]; angles = np.arange(0, 181, 5)
    # Synthesized feedforward (amplitude and angle): advance = delay + half a period of hold, minus the one-sample
    # lead of the PLL angle (it locks on the SOGI output). Rung 1: 1 + 0.5 = 1.5 (ideal angle); rung 4: 0.8 + 0.5 - 1 = 0.3.
    sets = [('rung 1, today (measured feedforward, advance 0.5)', RUNG1), ('rung 4, today', RUNG4),
            ('rung 1, synthesized feedforward, advance 1.5', {**RUNG1, 'ff': 'exact', 'adv': 1.5}),
            ('rung 4, synthesized feedforward, advance 0.3', {**RUNG4, 'ff': 'exact', 'adv': 0.3})]
    res = {name: [metrics(rg, lg, contact_deg=float(a), **{**BASE, **kw}) for a in angles] for name, kw in sets}
    out.mkdir(parents=True, exist_ok=True)
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(8, 6), sharex=True, facecolor='#fcfcfb')
    for (name, _), col in zip(sets, COLORS):
        a1.plot(angles, [m['peak10'] for m in res[name]], color=col, lw=1.5, marker='o', ms=3, label=name)
        a2.plot(angles, [m['settle_ms'] for m in res[name]], color=col, lw=1.5, marker='o', ms=3, label=name)
    a1.axhline(TARGET_PEAK, color='#52514e', lw=0.8, ls='--'); a1.axhline(ld.TRIP, color='#e34948', lw=0.8, ls=':')
    a2.axhline(TARGET_SETTLE_MS, color='#52514e', lw=0.8, ls='--')
    for ax in (a1, a2): style(ax)
    a1.set_ylabel('Peak line current, 10 ms (A)'); a2.set_ylabel('Settling ±0.05 A (ms)')
    a2.set_xlabel('Grid-voltage angle at the contact (°, 0 = rising zero crossing, 90 = positive peak)')
    a1.set_title(f'Contact angle sweep, {grid} grid (dashed: provisional target; dotted: 1.5 A trip)', loc='left', fontsize=11)
    a1.legend(frameon=False, fontsize=8); fig.tight_layout(); fig.savefig(out / 'angle_sweep.png', dpi=130); plt.close(fig)
    lines = header('D-GFL-03', 'contact angle', grid, rg, lg,
                   'Relay contact swept over 0–180° of the grid-voltage angle in 5° steps (the command 9.7 ms earlier), candidate C, current PI from the relay command; today\'s configuration and the synthesized feedforward found by D-GFL-02 (case j: amplitude and PLL angle; advance 1.5 periods on rung 1, 0.3 on rung 4 where the PLL angle already leads by one sample). 180–360° mirrors 0–180° (negative half-cycle). The contact angle does not change the linear loop: its margins are those of [D-GFL-01](../D-GFL-01_IEC/report.md) rung 1 and rung 4.')
    lines += ['![Angle sweep](angle_sweep.png)', '']
    for name, _ in sets:
        ms = res[name]; best = int(np.argmin([m['peak10'] for m in ms]))
        ok = [int(a) for a, m in zip(angles, ms) if m['meets']]
        lines += [f'## {name}', '',
                  f"Smallest peak at {angles[best]}°: {f(ms[best]['peak10'])} A, settling {f(ms[best]['settle_ms'])} ms. "
                  f"Angles meeting the provisional target: {', '.join(map(str, ok)) + '°' if ok else 'none'}.", '', *METRIC_HEAD]
        lines += [metric_row(f'{a}°', m) for a, m in zip(angles, ms) if a % 15 == 0 or a == angles[best]]
        lines.append('')
    (out / 'report.md').write_text('\n'.join(lines) + '\n'); print('\n'.join(lines[8:]))


def main():
    a = argparse.ArgumentParser(); a.add_argument('--test', choices=['02', '03'], required=True)
    a.add_argument('--grid', default='IEC'); a.add_argument('--out', type=Path, required=True); o = a.parse_args()
    (test02 if o.test == '02' else test03)(o.grid, o.out)


if __name__ == '__main__':
    main()
