{
	return arm_error;
}

bool safety_trips_source_active(void)
{
#if SAFETY_COMPARATOR_TRIPS > 0
	for (size_t i = 0; i < SAFETY_COMPARATOR_TRIPS; i++) {
		if ((armed_flt_mask & (1U << (trips[i].flt - 1U))) && comparator_active(&trips[i])) {
			return true;
		}
	}
#endif
	return false;
}

bool safety_trips_settle_and_check(void)
{
#if SAFETY_WATCHDOG_TRIPS > 0
	for (size_t i = 0; i < SAFETY_WATCHDOG_TRIPS; i++) {
		adc_of(awds[i].adc)->ISR = awd_flag(awds[i].awd);   /* sticky: clear, then see if it comes back */
	}
	k_busy_wait(200);   /* several conversions at any trigger rate above 10 kHz */
	for (size_t i = 0; i < SAFETY_WATCHDOG_TRIPS; i++) {
		if ((armed_flt_mask & (1U << (awds[i].flt - 1U))) &&
		    (adc_of(awds[i].adc)->ISR & awd_flag(awds[i].awd))) {
			return true;
		}
	}
#endif
	return safety_trips_source_active();
}

void safety_trips_clear(void)
{
	uint32_t m = armed_flt_mask;

	trip_flt_mask = 0U;
	HRTIM1->sCommonRegs.ICR = flt_to_hw(m);
	HRTIM1->sCommonRegs.IER |= flt_to_hw(m);
}

int safety_trips_check(void)
{
	if (!armed) {
		return 0;
	}
#if SAFETY_WATCHDOG_TRIPS > 0
	for (size_t i = 0; i < SAFETY_WATCHDOG_TRIPS; i++) {
		const struct watchdog_trip *w = &awds[i];
		ADC_TypeDef *a = adc_of(w->adc);
		uint32_t tr = (w->awd == 1U) ? (a->TR1 & (ADC_TR1_HT1 | ADC_TR1_LT1)) :
			      (w->awd == 2U) ? a->TR2 : a->TR3;
		uint32_t hshift = (w->awd == 1U) ? ADC_TR1_HT1_Pos : ADC_TR2_HT2_Pos;
		bool en = (w->awd == 1U) ? ((a->CFGR & ADC_CFGR_AWD1EN) != 0U) :
			  (w->awd == 2U) ? ((a->AWD2CR & (1U << w->channel)) != 0U) :
			  ((a->AWD3CR & (1U << w->channel)) != 0U);
		if (!en || tr != (((uint32_t)w->hi << hshift) | w->lo)) {
			safety_outputs_disable_all();
			safety_supervision_latch(SAFETY_FAULT_TRIP, 1U << 9 | i);
			return -1;
		}
	}
#endif
#if SAFETY_COMPARATOR_TRIPS > 0
	for (size_t i = 0; i < SAFETY_COMPARATOR_TRIPS; i++) {
		const struct comparator_trip *t = &trips[i];
		if (!(armed_flt_mask & (1U << (t->flt - 1U)))) {
			continue;
		}
		if (dac_dor(t->dac, t->dac_channel) != dac_now[i] || *dac_dhr(t->dac, t->dac_channel) != dac_now[i]) {
			/* A threshold changed behind the Safety API's back (ADR 0009). */
			safety_outputs_disable_all();
			safety_supervision_latch(SAFETY_FAULT_TRIP, 1U << 8 | i);
			return -1;
		}
	}
#endif
	return 0;
}

int safety_trips_count(void)
{
	return SAFETY_COMPARATOR_TRIPS;
}

int safety_trips_set_threshold(const char *sensor, bool high_bound, float value)
{
#if SAFETY_COMPARATOR_TRIPS > 0
	for (size_t i = 0; i < SAFETY_COMPARATOR_TRIPS; i++) {
		const struct comparator_trip *t = &trips[i];
		if (t->high_bound != high_bound || strcmp(t->sensor, sensor) != 0) {
			continue;
		}
		if (t->gain == 0.0f) {
			return -2;
		}
		float raw = (value - t->offset) / t->gain;
		int32_t code = (int32_t)(raw + 0.5f);
		if (code < 0 || code > (int32_t)DAC_FULL_SCALE) {
			return -3;
		}
		/* Tighten only: a lower high limit, a higher low limit (ADR 0009). */
		if (high_bound ? (code > (int32_t)dac_now[i]) : (code < (int32_t)dac_now[i])) {
			return -1;
		}
		dac_now[i] = (uint16_t)code;
		dac_set(t, (uint16_t)code);
		return 0;
	}
#else
	ARG_UNUSED(sensor);
	ARG_UNUSED(high_bound);
	ARG_UNUSED(value);
#endif
	return -4;   /* no comparator trip on this bound */
}

int safety_trips_dac_code(int index)
{
#if SAFETY_COMPARATOR_TRIPS > 0
	if (index >= 0 && index < SAFETY_COMPARATOR_TRIPS) {
		return dac_now[index];
	}
#else
	ARG_UNUSED(index);
#endif
	return -1;
}
