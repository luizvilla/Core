static volatile uint32_t checkpoints;
static uint32_t period_cycles;
static uint32_t last_period_cyc;
static uint32_t fast_periods;

void safety_supervision_checkpoint(uint32_t cp)
{
	checkpoints |= cp;
}

/* ---- Kernel liveness (ADR 0009, #23 C10) ------------------------------------
 * The control task runs at zero latency: irq_lock() in a thread does not stop
 * it, so it would feed the watchdog while no thread runs. The run-time
 * self-test work (system work queue, every 10 ms) stamps the cycle counter;
 * the feed refuses when the stamp is older than
 * CONFIG_OWNTECH_SAFETY_KERNEL_TIMEOUT_US. A thread of its own at 1 ms cost
 * about 3 % of the CPU and 3 us of task-start jitter (L0-TOV, 2026-11-19):
 * the work queue already runs, and its stopping also stops the self-tests.
 * Without the run-time self-tests (development mode only) nothing stamps and
 * the check stays off. */
static volatile uint32_t kernel_stamp;        /* DWT cycles at the last stamp, 0 before the first */
static volatile uint32_t kernel_gap_max_cyc;
static uint32_t kernel_timeout_cyc = 0xFFFFFFFFU;   /* set when a control task attaches */

void safety_supervision_kernel_alive(void)
{
	uint32_t now = DWT->CYCCNT, last = kernel_stamp;
	if (last != 0U && now - last > kernel_gap_max_cyc) {
		kernel_gap_max_cyc = now - last;
	}
	kernel_stamp = (now != 0U) ? now : 1U;
}

void safety_supervision_liveness(safety_liveness_t *out)
{
	out->kernel_gap_max_us = kernel_gap_max_cyc / (SystemCoreClock / 1000000U);
	out->kernel_timeout_us = CONFIG_OWNTECH_SAFETY_KERNEL_TIMEOUT_US;
}

/* Program flow (H.2 1.3): fed only when both checkpoints of the period were
 * passed; a period that skipped one lets the watchdog reset the MCU.
 * Interrupt rate (H.2 2): three periods in a row shorter than half the declared
 * one mean the control interrupt fires far more often than configured (a
 * missing interrupt is the watchdog's job). */
void safety_supervision_feed(void)
{
	uint32_t now = DWT->CYCCNT;

	if (critical_feeder && kernel_stamp != 0U) {
		if (now - kernel_stamp > kernel_timeout_cyc) {
			/* The work queue did not run: record why, stop the outputs, let the watchdog reset. */
			if (latched == SAFETY_FAULT_NONE) {
				safety_supervision_latch(SAFETY_FAULT_WATCHDOG, SAFETY_WATCHDOG_KERNEL);
				safety_emergency_stop();
			}
			checkpoints = 0U;
			last_period_cyc = now;
			return;
		}
	}

	if (critical_feeder && period_cycles != 0U && last_period_cyc != 0U) {
		if (now - last_period_cyc < period_cycles / 2U) {
			if (++fast_periods >= 3U && latched == SAFETY_FAULT_NONE) {
				safety_supervision_latch(SAFETY_FAULT_SELFTEST, SAFETY_SELFTEST_IRQ_RATE);
				safety_emergency_stop();
			}
		} else {
			fast_periods = 0U;
		}
	}
	last_period_cyc = now;
	if (safety_selftest_injected() & SAFETY_SELFTEST_INJECT_FLOW) {
		checkpoints &= ~SAFETY_CP_USER_TASK;   /* test hook: a skipped checkpoint */
	}
	if (armed && (!critical_feeder || checkpoints == SAFETY_CP_ALL)) {
		IWDG->KR = IWDG_KEY_FEED;
	}
	checkpoints = 0U;
}

/* Smallest prescaler and reload whose shortest timeout (LSI at its fastest)
 * still covers 3 control periods; never shorter than the default. */
static void iwdg_timing_for_period(uint32_t period_us)
{
	uint64_t need_us = 3ULL * period_us;

	iwdg_pr = IWDG_PRESCALER_DIV4;
	iwdg_rlr = IWDG_RELOAD;
	for (uint32_t pr = 0U; pr <= 6U; pr++) {
		uint64_t div = 4ULL << pr;
		/* ticks so that ticks * div / LSI_MAX >= need_us */
		uint64_t ticks = (need_us * LSI_MAX_HZ + div * 1000000ULL - 1U)
				 / (div * 1000000ULL);
		if (ticks <= (uint64_t)IWDG_RELOAD_MAX + 1U) {
			if (pr > iwdg_pr || ticks - 1U > iwdg_rlr) {
				iwdg_pr = pr;
				iwdg_rlr = (uint32_t)(ticks - 1U);
				if (pr == IWDG_PRESCALER_DIV4 && iwdg_rlr < IWDG_RELOAD) {
					iwdg_rlr = IWDG_RELOAD;
				}
			}
			return;
		}
	}
	iwdg_pr = 6U;
	iwdg_rlr = IWDG_RELOAD_MAX;
}

static void iwdg_apply(void)
{
	IWDG->KR = IWDG_KEY_UNLOCK;
	IWDG->PR = iwdg_pr;
	IWDG->RLR = iwdg_rlr;
	while (IWDG->SR != 0U) {
	}
	IWDG->KR = IWDG_KEY_FEED;
}

uint32_t safety_supervision_watchdog_timeout_us(void)
{
	return (uint32_t)((4ULL << iwdg_pr) * (iwdg_rlr + 1U) * 1000000ULL / LSI_MIN_HZ);
}

void safety_supervision_feeder_attach(uint32_t period_us)
{
	period_cycles = period_us * (SystemCoreClock / 1000000U);
	kernel_timeout_cyc = CONFIG_OWNTECH_SAFETY_KERNEL_TIMEOUT_US * (SystemCoreClock / 1000000U);
	last_period_cyc = 0U;
	fast_periods = 0U;
	iwdg_timing_for_period(period_us);
	if (armed) {
		iwdg_apply();
	}
	critical_feeder = true;
	/* The control task feeds from now on: the kernel timer would only add a
	 * SysTick interrupt every 200 us (measured: 9 % of the CPU and extra
	 * task-start jitter with a 50 us task, #27). */
	k_timer_stop(&feed_timer);
}

void safety_supervision_feeder_detach(void)
{
	critical_feeder = false;
	if (armed) {
		IWDG->KR = IWDG_KEY_FEED;   /* no gap until the timer's first tick */
		k_timer_start(&feed_timer, K_USEC(200), K_USEC(200));
	}
}

